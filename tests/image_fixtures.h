// FNV-1a (32-bit), used to pin translator output byte for byte.
inline std::uint32_t fnv1a(const std::vector<std::uint8_t>& bytes)
{
    std::uint32_t h = 0x811C9DC5u;
    for (const std::uint8_t b : bytes) {
        h ^= b;
        h *= 0x01000193u;
    }
    return h;
}

